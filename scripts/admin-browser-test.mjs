import { chromium } from "playwright";
import assert from "node:assert/strict";
import { readFile, mkdir } from "node:fs/promises";
import path from "node:path";

// Explicit disposable loopback backend only. This test never substitutes mock data in the app.
const base = new URL(process.env.SPD_E2E_BASE_URL || "http://127.0.0.1:18765");
assert.equal(base.hostname, "127.0.0.1", "Browser test writes must target a disposable loopback backend");
assert.ok(process.env.SPD_E2E_PASSWORD_FILE, "Provide the temporary bootstrap password file");
const password = (await readFile(process.env.SPD_E2E_PASSWORD_FILE, "utf8")).trim();
const username = process.env.SPD_E2E_ADMIN || "auditadmin";
const screenshots = process.env.SPD_SCREENSHOTS_DIR || path.resolve("docs/premium/screenshots");
await mkdir(screenshots, { recursive: true });
const browser = await chromium.launch({ headless: true,
  ...(process.env.SPD_BROWSER_EXECUTABLE ? { executablePath: process.env.SPD_BROWSER_EXECUTABLE } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: "fa-IR" });
const page = await context.newPage();
const errors = [];
page.on("pageerror", e => errors.push(e.name));
async function shot(name) { await page.screenshot({ path: path.join(screenshots, name + ".png"), fullPage: true }); }
try {
  await page.goto(new URL("/admin", base).href);
  await page.locator("#login").waitFor({ state: "visible" });
  await shot("01-login");
  await page.locator('#login-form [name="username"]').fill(username);
  await page.locator('#login-form [name="password"]').fill("incorrect-test-password");
  await page.locator('#login-form button').click();
  await page.getByText("نام کاربری یا رمز معتبر نیست", { exact: true }).waitFor();
  await page.locator('#login-form [name="password"]').fill(password);
  await page.locator('#login-form button').click();
  await page.locator("#workspace").waitFor({ state: "visible" });
  await page.getByRole("heading", { name: "اتصال‌های گزارش‌شده", exact: true }).waitFor();
  await shot("02-dashboard");
  const session = await (await context.request.get(new URL("/admin/api/session", base).href)).json();
  const csrf = session.data.csrfToken;
  const forbidden = await context.request.post(new URL("/admin/api/logout", base).href,
    { headers: { Origin: "https://foreign.test", "X-CSRF-Token": csrf }, data: {} });
  assert.equal(forbidden.status(), 403);
  await page.locator('a[href="#users"]').click();
  await page.getByRole("heading", { name: "ساخت حساب", exact: true }).waitFor();
  await shot("03-users");
  const accountName = "browser-" + Date.now().toString(36);
  const create = page.locator("section.card").filter({ has: page.getByRole("heading", { name: "ساخت حساب", exact: true }) });
  await create.locator('[name="username"]').fill(accountName);
  await create.locator('[name="password"]').fill(password);
  await create.locator('button[type="submit"]').click();
  await page.waitForURL(/#user\/[a-f0-9-]+$/);
  await page.getByRole("heading", { name: accountName, exact: true }).waitFor();
  await page.getByText(/PASARGUARD_NOT_CONFIGURED/).first().waitFor({ timeout: 30000 });
  await shot("04-user-detail");
  await page.locator('a[href="#plans"]').click();
  await page.getByRole("heading", { name: "بدون انقضای زمانی", exact: true }).waitFor();
  await shot("05-plans");
  // Create a real private plan in this disposable DB, not runtime fallback/production data.
  const planId="BROWSER_TRIAL_10GB";
  const planName="Browser Trial 10 GB";
  const newPlan=page.locator("section.card").filter({has:page.getByRole("heading",{name:"ساخت پلن جدید",exact:true})});
  await newPlan.locator('[name="id"]').fill(planId);
  await newPlan.locator('[name="title"]').fill(planName);
  await newPlan.locator('[name="days"]').fill("7");
  await newPlan.locator('[name="quota"]').fill("10000000000");
  assert.equal(await newPlan.locator('[name="published"]').isChecked(),false);
  await newPlan.locator('button[type="submit"]').click();
  const privatePlan=page.locator("section.card").filter({has:page.getByRole("heading",{name:planName,exact:true})});
  await privatePlan.waitFor();
  const publicProduct=await (await context.request.get(new URL("/v1/product",base).href)).json();
  assert.equal(publicProduct.data.plans.some(p=>p.id===planId),false);
  await privatePlan.locator('[name="published"]').check();
  await privatePlan.locator('button[type="submit"]').click();
  await page.locator('#toast').filter({hasText:'حداکثر سه پلن'}).waitFor();
  await privatePlan.locator('[name="published"]').uncheck();
  await privatePlan.locator('[name="isAssignable"]').uncheck();
  await privatePlan.locator('button[type="submit"]').click();
  await page.getByText("تعریف پلن ذخیره شد",{exact:true}).waitFor();
  await page.locator('a[href="#users"]').click();
  await page.getByRole("heading",{name:"ساخت حساب",exact:true}).waitFor();
  assert.equal(await page.locator(`select[name="planId"] option[value="${planId}"]`).count(),0);
  await page.locator('a[href="#plans"]').click();
  await privatePlan.waitFor();
  await privatePlan.locator('[name="isAssignable"]').check();
  await privatePlan.locator('button[type="submit"]').click();
  await page.getByText("تعریف پلن ذخیره شد",{exact:true}).waitFor();
  await page.locator('a[href="#users"]').click();
  const trialCreate=page.locator("section.card").filter({has:page.getByRole("heading",{name:"ساخت حساب",exact:true})});
  await trialCreate.locator('[name="username"]').fill("trial-"+Date.now().toString(36));
  await trialCreate.locator('[name="password"]').fill(password);
  await trialCreate.locator('[name="planId"]').selectOption(planId);
  await trialCreate.locator('button[type="submit"]').click();
  await page.waitForURL(/#user\/[a-f0-9-]+$/);
  const trialId=new URL(page.url()).hash.split('/')[1];
  const trialAccount=await (await context.request.get(new URL('/admin/api/users/'+trialId,base).href)).json();
  assert.equal(trialAccount.data.planId,planId);
  assert.equal(trialAccount.data.requested.quotaBytes,10000000000);
  await shot("09-private-plan-assigned");
  await page.locator('a[href="#free"]').click();
  await page.getByRole("heading", { name: "کاتالوگ واقعی VPN Gate", exact: true }).waitFor();
  await shot("06-free");
  await page.locator('a[href="#audit"]').click();
  await page.getByRole("heading", { name: "تاریخچهٔ عملیات مدیریتی", exact: true }).waitFor();
  await page.getByRole("cell", { name: "CREATE_REQUESTED", exact: true }).first().waitFor();
  await shot("07-audit");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('a[href="#dashboard"]').click();
  await page.getByRole("heading", { name: "اتصال‌های گزارش‌شده", exact: true }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
  await shot("08-mobile");
  await page.locator("#logout").click();
  await page.locator("#login").waitFor({ state: "visible" });
  assert.equal((await context.request.get(new URL("/admin/api/users", base).href)).status(), 401);
  assert.deepEqual(errors, []);
  console.log("PASS: login/CSRF, private plan creation/assignment, publication limit, assignment selector, account pending/failed, navigation, audit, responsive layout, logout; 9 screenshots");
} finally { await context.close(); await browser.close(); }
